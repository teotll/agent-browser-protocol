  // Action complete wait state for after-screenshots
  // Default mode ("action_complete"): Waits for networkidle2 AND 500ms AND load AND DOMContentLoaded
  // Extended modes: "text", "url", "network_idle", "time"
  struct ActionCompleteWaiter {
    ActionCompleteWaiter();
    ~ActionCompleteWaiter();
    ActionCompleteWaiter(const ActionCompleteWaiter&) = delete;
    ActionCompleteWaiter& operator=(const ActionCompleteWaiter&) = delete;

    std::string tab_id;
    base::TimeTicks action_start_time;
    base::OnceClosure on_complete;

    // Wait type: "action_complete" (default), "text", "url", "network_idle", "time"
    std::string wait_type = "action_complete";

    // Condition flags for action_complete mode
    bool load_fired = false;
    bool dom_content_loaded_fired = false;
    bool first_paint_fired = false;
    bool network_idle = false;
    bool min_time_elapsed = false;
    bool min_wait_timer_started = false;

    // Observer for page lifecycle events (destroyed with waiter)
    std::unique_ptr<AbpPageLoadObserver> page_load_observer;

    // Network tracking (networkidle2 = ≤2 connections for 500ms)
    int active_requests = 0;
    base::TimeTicks last_network_activity;

    // Timeout
    base::TimeTicks timeout_time;

    // Minimum wait time (configurable per action)
    base::TimeDelta min_wait_time = base::Milliseconds(500);

    // Request ID tracking (for action-triggered network requests)
    std::set<std::string> active_request_ids;        // all in-flight request IDs (filtered)
    std::set<std::string> tracked_requests;          // snapshot taken at min_wait boundary
    bool tracking_snapshot_taken = false;            // snapshot done
    bool tracked_requests_resolved = false;          // all tracked done or timed out
    bool tracking_timed_out = false;                 // timeout triggered (for event)
    base::TimeDelta request_tracking_timeout = base::Seconds(1);

    // Post-tracking settle (Phase 3)
    bool post_tracking_settle_started = false;
    bool post_tracking_settled = false;
    base::TimeDelta post_tracking_settle_time = base::Milliseconds(150);

    // Text wait fields
    std::string wait_text;
    bool text_found = false;

    // URL wait fields
    std::string wait_url_pattern;
    bool url_matched = false;

    // Time wait fields (deferred: timer starts after page load)
    int time_wait_ms = 0;
    bool time_wait_started = false;
    bool time_wait_elapsed = false;

    bool IsComplete() const {
      if (wait_type == "action_complete") {
        return load_fired && dom_content_loaded_fired &&
               first_paint_fired && min_time_elapsed &&
               tracked_requests_resolved && post_tracking_settled;
      } else if (wait_type == "network_idle") {
        return network_idle;
      } else if (wait_type == "text") {
        return text_found;
      } else if (wait_type == "url") {
        return url_matched;
      } else if (wait_type == "time") {
        return time_wait_elapsed;
      }
      return false;
    }
  };

